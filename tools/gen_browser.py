#!/usr/bin/env python3
"""Embed the browser target and Go runtime without adding runtime files.

Input Wasm is built separately. Gzip has a fixed timestamp, so regenerating
from identical inputs is byte-for-byte deterministic. No shared package
imports browserassets; this prevents the embedded Wasm from embedding itself.
"""
import base64
import gzip
import pathlib
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parent.parent
goroot = pathlib.Path(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip())
files = {
    "wasm": root / "try/app.wasm",
    "runtime": goroot / "lib/wasm/wasm_exec.js",
    "bootstrap": root / "tools/browser_bootstrap.js",
}
if '--pack-only' in sys.argv:
    (root / 'try/app.wasm.gz').write_bytes(gzip.compress(files['wasm'].read_bytes(), mtime=0))
    raise SystemExit(0)
rows = ['module browserassets', '', '-- GENERATED by tools/gen_browser.py; native server assets only.',
        'import "bytes"', 'import "compress/gzip"', 'import "encoding/base64"', 'import "io"', '',
        'let decode (encoded : String) : Slice Byte := do {',
        '  let data, err := base64.StdEncoding.DecodeString encoded;',
        '  if err != nil then panic err else ();',
        '  data', '}', '',
        'let unpack (data : Slice Byte) : Slice Byte := do {',
        '  let reader, failure := gzip.NewReader (bytes.NewReader data);',
        '  if failure != nil then panic failure else ();',
        '  defer reader.Close ();',
        '  let decoded, readErr := io.ReadAll reader;',
        '  if readErr != nil then panic readErr else ();', '  decoded', '}', '']
for name, path in files.items():
    data = path.read_bytes()
    encoded = base64.b64encode(gzip.compress(data, mtime=0)).decode()
    if name == 'wasm':
        rows += [f'let CompressedWASM : Slice Byte := decode "{encoded}"',
                 'let wasm : Slice Byte := unpack CompressedWASM', '']
    else:
        rows += [f'let {name} : Slice Byte := unpack (decode "{encoded}")', '']
    print(f"{name}: {len(data)} bytes; {len(encoded)} embedded base64 bytes")
rows += ['let Asset (path : String) : Slice Byte :=',
         '  if path == "/app.wasm" then wasm',
         '  else if path == "/app.wasm.gz" then CompressedWASM',
         '  else if path == "/wasm_exec.js" then runtime',
         '  else if path == "/browser.js" then bootstrap',
         '  else make (Slice Byte) 0', '']
out = root / 'browserassets'
content = '\n'.join(rows)
if '--check' in sys.argv:
    if not (out / 'assets.goml').exists() or (out / 'assets.goml').read_text() != content:
        raise SystemExit('Browser assets are stale. Run make browser-assets.')
else:
    out.mkdir(exist_ok=True)
    (out / 'assets.goml').write_text(content)
    (root / 'try/app.wasm.gz').write_bytes(gzip.compress(files['wasm'].read_bytes(), mtime=0))
